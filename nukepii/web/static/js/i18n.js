  function getLang() {
    try {
      var l = localStorage.getItem("nukepii_lang");
      if (l === "en" || l === "tr") return l;
    } catch (e) {}
    return "tr";
  }

  function setLang(lang) {
    try {
      localStorage.setItem("nukepii_lang", lang);
    } catch (e) {}
    document.documentElement.lang = lang;
  }

  function fill(str, vars) {
    if (!vars) return str;
    return String(str).replace(/\{(\w+)\}/g, function (m, k) {
      return vars[k] !== undefined ? vars[k] : m;
    });
  }

  function t(key, vars) {
    var lang = getLang();
    var s = (STR[lang] && STR[lang][key]) || STR.tr[key] || key;
    return fill(s, vars);
  }

